/// Screen-width breakpoints used across the app.
///   compact  : phones           (< 600)
///   medium   : large phones / tablets / small windows (600 – 999)
///   expanded : laptops & desktops (>= 1000) -> sidebar layout
class Breakpoints {
  Breakpoints._();
  static const double medium = 600;
  static const double expanded = 1000;
}
